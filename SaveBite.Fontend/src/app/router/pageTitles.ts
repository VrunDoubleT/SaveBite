const titleRoutes = Object.entries(titles).map(([key, title]) => ({
  path: APP_PATHS[key as keyof typeof titles],
  handle: title,
}));

export function getPageTitle(pathname: string): string {
  const matches = matchRoutes(titleRoutes, pathname);
  const title = matches?.at(-1)?.route.handle ?? "Page Not Found";
  return `${title} | SaveBite`;
}
