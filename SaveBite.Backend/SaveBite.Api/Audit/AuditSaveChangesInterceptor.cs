using System.Reflection;
using System.Text.Json;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Diagnostics;
using SaveBite.Backend.Constants;
using SaveBite.Backend.Helpers;
using SaveBite.Backend.Models.Entities;
using SaveBite.Backend.Models.Enums;

namespace SaveBite.Backend.Audit;

public class AuditSaveChangesInterceptor(IAuditContext ctx) : SaveChangesInterceptor
{

    public override ValueTask<InterceptionResult<int>> SavingChangesAsync(
        DbContextEventData e,
        InterceptionResult<int> result,
        CancellationToken ct = default)
    {
        if (e.Context is not null && ctx.Enabled)
        {
            AddAuditRecords(e.Context);
        }

        return base.SavingChangesAsync(e, result, ct);
    }

    public override InterceptionResult<int> SavingChanges(
        DbContextEventData e,
        InterceptionResult<int> result)
    {
        if (e.Context is not null && ctx.Enabled)
        {
            AddAuditRecords(e.Context);
        }

        return base.SavingChanges(e, result);
    }

    private void AddAuditRecords(DbContext db)
    {
        db.ChangeTracker.DetectChanges();

        var entries = db.ChangeTracker.Entries()
            .Where(x => x.State is EntityState.Added
                                or EntityState.Modified
                                or EntityState.Deleted)
            .Where(x => x.Entity is not AuditLog)
            .Where(x => x.Entity.GetType().GetCustomAttribute<NoAuditAttribute>() is null)
            .ToList(); // Snapshot before adding audit entries to the tracker.

        // Rebuild only entries generated by this interceptor on SaveChanges retries.
        foreach (var log in _pending.ToArray())
            if (db.Entry(log).State == EntityState.Added) db.Entry(log).State = EntityState.Detached;
        _pending.Clear();
        var manual = db.ChangeTracker.Entries<AuditLog>()
            .Where(x => x.State == EntityState.Added)
            .Select(x => AuditPolicy.ManualTarget(x.Entity, db)).ToHashSet();
        foreach (var entry in entries)
        {
            var business = AuditBusinessEvents.FromHistory(entry, ctx);
            if (business == null || manual.Contains((business.TargetType, business.TargetId))) continue;
            db.Set<AuditLog>().Add(business);
            _pending.Add(business);
        }
        // Multiple lifecycle transitions can occur in one save; preserve each event,
        // but suppress the redundant root/children CRUD snapshot for that target.

        var groups = entries.Select(entry => (Entry: entry, Target: AuditPolicy.Target(entry, db)))
            .Where(x => x.Target.HasValue && x.Target.Value.Id != Guid.Empty)
            .GroupBy(x => x.Target!.Value);
        foreach (var group in groups)
        {
            if (manual.Contains(group.Key)) continue;
            var changes = group.Select(x => (x.Entry, Change: Build(x.Entry)))
                .Where(x => x.Change.action != null).ToList();
            if (changes.Count == 0) continue;
            var root = changes.FirstOrDefault(x => x.Entry.Metadata.ClrType.Name == group.Key.Type);
            var operation = root.Entry == null ? AuditActionTypes.Update : root.Change.action!;
            var oldValues = new Dictionary<string, object?>();
            var newValues = new Dictionary<string, object?>();
            foreach (var change in changes)
            {
                var isRoot = change.Entry.Metadata.ClrType.Name == group.Key.Type;
                var key = isRoot ? "Fields" : $"{change.Entry.Metadata.ClrType.Name}:{change.Entry.Property("Id").CurrentValue}";
                if (change.Change.oldJson != null) oldValues[key] = JsonSerializer.Deserialize<JsonElement>(change.Change.oldJson);
                if (change.Change.newJson != null) newValues[key] = JsonSerializer.Deserialize<JsonElement>(change.Change.newJson);
            }
            var events = _pending.Where(x => x.TargetType == group.Key.Type && x.TargetId == group.Key.Id).ToList();
            if (events.Count > 0)
            {
                // Keep the explicit decision plus its root/child changes in one record.
                foreach (var business in events)
                {
                    business.OldValuesJson = Combine(business.OldValuesJson, oldValues);
                    business.NewValuesJson = Combine(business.NewValuesJson, newValues);
                }
                continue;
            }
            var status = root.Entry?.Properties.FirstOrDefault(x => x.Metadata.Name == "Status" && x.IsModified && !Equals(x.OriginalValue, x.CurrentValue));
            // Preserve meaningful lifecycle names until these commands provide an explicit writer entry.
            var action = operation == AuditActionTypes.Delete ? operation
                : status != null ? $"STATUS_{status.CurrentValue}" : operation;
            var log = new AuditLog
            {
                Id = Guid.NewGuid(),
                ActorUserId = ctx.ActorUserId,
                ActorType = ctx.ActorType,
                Action = AuditActionTypes.Format(group.Key.Type, action),
                TargetType = group.Key.Type,
                TargetId = group.Key.Id,
                OldValuesJson = oldValues.Count == 0 ? null : AuditJson.SerializeSafe(oldValues),
                NewValuesJson = newValues.Count == 0 ? null : AuditJson.SerializeSafe(newValues),
                Reason = ctx.Reason,
                CorrelationId = ctx.CorrelationId,
                CreatedAt = DateTime.UtcNow
            };
            db.Set<AuditLog>().Add(log);
            _pending.Add(log);
        }
    }

    private static string? Combine(string? decision, Dictionary<string, object?> changes)
    {
        if (changes.Count == 0) return decision;
        return AuditJson.SerializeSafe(new
        {
            Decision = decision == null ? (JsonElement?)null : JsonSerializer.Deserialize<JsonElement>(decision),
            Changes = changes
        });
    }

    private readonly List<AuditLog> _pending = [];

    private static (string? action, string? oldJson, string? newJson) Build(EntityEntry entry)
    {
        var props = entry.Properties
            .Where(p => p.Metadata.PropertyInfo?.IsDefined(typeof(AuditIgnoreAttribute)) != true)
            .Where(p => !AuditPolicy.Ignore(p.Metadata.Name) && !AuditPayloadSanitizer.IsSensitiveKey(p.Metadata.Name))
            .ToList();

        switch (entry.State)
        {
            case EntityState.Added:
                return (AuditActionTypes.Create, null, Serialize(props, p => p.CurrentValue));

            case EntityState.Deleted:
                return (AuditActionTypes.Delete, Serialize(props, p => p.OriginalValue), null);

            case EntityState.Modified:
                var changed = props
                    .Where(p => p.IsModified && !Equals(p.OriginalValue, p.CurrentValue))
                    .ToList();
                if (changed.Count == 0) return (null, null, null);

                var isSoftDelete = entry.Entity is ProductFeedback && changed.Any(p => p.Metadata.Name == "Status" && Equals(p.CurrentValue, FeedbackStatus.HiddenByCustomer))
                    || changed.Any(p =>
                    (p.Metadata.Name == "IsDeleted" && p.CurrentValue is true) ||
                    (p.Metadata.Name == "DeletedAt" && p.CurrentValue is not null && p.OriginalValue is null));

                return (isSoftDelete ? AuditActionTypes.Delete : AuditActionTypes.Update,
                    Serialize(changed, p => p.OriginalValue),
                    Serialize(changed, p => p.CurrentValue));
        }

        return (null, null, null);
    }

    private static string Serialize(IEnumerable<PropertyEntry> props, Func<PropertyEntry, object?> pick)
    {
        var dict = new Dictionary<string, object?>();
        foreach (var p in props)
        {
            dict[p.Metadata.Name] = pick(p);
        }

        return AuditJson.Serialize(dict);
    }
}
